package com.freightfox.githubsearcher.dto;

import java.time.LocalDateTime;

/**
 * Public representation of a stored GitHub repository, returned to API consumers.
 */
public class RepositoryResponse {

    private Long id;
    private String name;
    private String description;
    private String owner;
    private String language;
    private Long stars;
    private Long forks;
    private LocalDateTime lastUpdated;

    public RepositoryResponse() {
    }

    public RepositoryResponse(Long id, String name, String description, String owner,
                              String language, Long stars, Long forks, LocalDateTime lastUpdated) {
        this.id = id;
        this.name = name;
        this.description = description;
        this.owner = owner;
        this.language = language;
        this.stars = stars;
        this.forks = forks;
        this.lastUpdated = lastUpdated;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getOwner() {
        return owner;
    }

    public void setOwner(String owner) {
        this.owner = owner;
    }

    public String getLanguage() {
        return language;
    }

    public void setLanguage(String language) {
        this.language = language;
    }

    public Long getStars() {
        return stars;
    }

    public void setStars(Long stars) {
        this.stars = stars;
    }

    public Long getForks() {
        return forks;
    }

    public void setForks(Long forks) {
        this.forks = forks;
    }

    public LocalDateTime getLastUpdated() {
        return lastUpdated;
    }

    public void setLastUpdated(LocalDateTime lastUpdated) {
        this.lastUpdated = lastUpdated;
    }
}
